// Rewrites eslint.boundaries.baseline.js with the files that still break a feature boundary.
// Run after fixing imports:  node scripts/gen-boundary-baseline.mjs   (shrink-only: commit the smaller list)
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const r = spawnSync('npx', ['eslint', 'src/features', '-f', 'json'], {
  cwd: root, encoding: 'utf8', shell: true, maxBuffer: 1 << 27,
  env: { ...process.env, BOUNDARY_NO_BASELINE: '1' },
})
const files = JSON.parse(r.stdout)
  .filter((f) => f.messages.some((m) => m.ruleId === 'no-restricted-imports'))
  .map((f) => path.relative(root, f.filePath).split(path.sep).join('/'))
  .sort()
const body = `// GENERATED by scripts/gen-boundary-baseline.mjs - files that still import across feature boundaries (shrink-only).\nexport const BASELINE_FILES = [\n${files.map((f) => `  '${f}',`).join('\n')}\n]\n`
writeFileSync(path.join(root, 'eslint.boundaries.baseline.js'), body)
console.log(`${files.length} baseline files`)
