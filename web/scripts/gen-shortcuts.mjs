// Generates docs/SHORTCUTS.md by scanning src/ for keyboard bindings.
// Usage (from web/):  node scripts/gen-shortcuts.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const SRC = new URL("../src", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const OUT = new URL("../../docs/SHORTCUTS.md", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(jsx|js)$/.test(name)) files.push(p);
  }
})(SRC);

// "combo": "Ctrl+D"  /  combo: "F2"  and helper calls
const COMBO = /combo:\s*[`"']([^`"']+)[`"']/g;
const HOOK = /useShortcuts|useRegisteredShortcuts|dialogBindings|tabBindings|helpBinding/;
const CLICK = /onClick=|onSubmit=/;

const rows = [];
const noKeys = [];
for (const f of files) {
  const text = readFileSync(f, "utf8");
  const rel = relative(SRC, f).split(sep).join("/");
  const combos = [...new Set([...text.matchAll(COMBO)].map((m) => m[1]))];
  const helpers = [];
  if (/dialogBindings\(/.test(text)) helpers.push("Ctrl+D", "Enter", "Escape");
  if (/tabBindings\(/.test(text)) helpers.push("Alt+1..9");
  if (/helpBinding\(/.test(text)) helpers.push("F1");
  const all = [...new Set([...combos, ...helpers])];
  if (all.length) rows.push({ rel, all });
  else if (/\.jsx$/.test(f) && CLICK.test(text) && !HOOK.test(text)) noKeys.push(rel);
}

rows.sort((a, b) => a.rel.localeCompare(b.rel));
const area = (r) => r.split("/").slice(0, r.startsWith("features/") ? 3 : 1).join("/");

let md = "# Keyboard shortcuts\n\n";
md += "_Generated by `web/scripts/gen-shortcuts.mjs` from the bindings in `web/src`. Do not edit by hand._\n\n";
md += "Conventions: F2 new, F3 secondary new, Ctrl+D save/confirm, Ctrl+A next, Ctrl+Z previous, ";
md += "Enter confirm, Escape close, F1 help (lists every active binding), Alt+1..9 tabs, ";
md += "Alt+Shift+1..9 sidebar sections.\n\n";
let last = "";
for (const r of rows) {
  const a = area(r.rel);
  if (a !== last) { md += `\n## ${a}\n\n`; last = a; }
  md += `- \`${r.rel.slice(a.length + 1) || r.rel}\`: ${r.all.map((c) => `\`${c}\``).join(", ")}\n`;
}
md += "\n## Files with mouse actions and no keyboard binding\n\n";
md += "These components have click handlers but register no shortcuts themselves (they are reached through ";
md += "the keyboard flow of their parent page/dialog, or still need a binding):\n\n";
for (const n of noKeys.sort()) md += `- \`${n}\`\n`;
writeFileSync(OUT, md);
console.log(`bindings in ${rows.length} files; ${noKeys.length} files without bindings -> ${OUT}`);
