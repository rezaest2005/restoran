#!/usr/bin/env python
"""
Generate things from ``dashboard/bizsuite/module_registry.py`` (the single source of truth). Standard library only.

  python scripts/gen_module_docs.py --baseline   rewrite bizsuite/module_violations_baseline.py (shrink it after decoupling)
  python scripts/gen_module_docs.py --docs       refresh the generated tables inside docs/MODULES.md
  python scripts/gen_module_docs.py --stats      print violation counts per module pair (raw coupling vs rule violations)
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "dashboard"))

from bizsuite import module_boundaries as mb, module_registry as reg  # noqa: E402

BASELINE_FILE = os.path.join(ROOT, "dashboard", "bizsuite", "module_violations_baseline.py")
DOC_FILE = os.path.join(ROOT, "docs", "MODULES.md")
BEGIN, END = "<!-- BEGIN GENERATED:{} -->", "<!-- END GENERATED:{} -->"


def write_baseline():
    found, unowned = mb.collect()
    assert not unowned, unowned
    lines = [
        '"""',
        "Known module-boundary violations (shrink-only). GENERATED by scripts/gen_module_docs.py --baseline.",
        "",
        "tests/test_module_boundaries.py fails when code has a violation that is not listed here AND when a listed",
        "one no longer exists. Fix a violation (public API / domain event), then regenerate. Never add by hand.",
        "",
        "Row: (source file, source module, target module, kind, imported name)",
        "kind: dep = no declared edge / core->business; internal = not in the target's public_api; model = foreign model",
        '"""',
        "BASELINE = {",
    ]
    for row in sorted(found, key=lambda r: (r[1], r[2], r[0], r[4])):
        lines.append("    " + repr(row) + ",")
    lines.append("}")
    with open(BASELINE_FILE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"baseline: {len(found)} violations written")


def pair_table(counts) -> str:
    rows = ["| from | to | count |", "|---|---|---|"]
    for (s, d), n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        rows.append(f"| {s} | {d} | {n} |")
    return "\n".join(rows)


def stats():
    raw, _ = mb.collect(raw=True)
    cur, _ = mb.collect()
    print(f"raw cross-module imports: {len(raw)} in {len(mb.pair_counts(raw))} pairs")
    print(f"rule violations (baseline): {len(cur)} in {len(mb.pair_counts(cur))} pairs")
    print(pair_table(mb.pair_counts(cur)))


def module_table() -> str:
    rows = ["| module | tier | owner files | public interface | frontend | tests |", "|---|---|---|---|---|---|"]
    for name, m in reg.MODULES.items():
        rows.append("| {} | {} | {} | {} | {} | {} |".format(
            name, m["tier"], "<br>".join(f"`{f}`" for f in m["files"]) or "-",
            "<br>".join(f"`{f}`" for f in m["public_api"]) or "-",
            "<br>".join(f"`{f}`" for f in m["frontend"]) or "-",
            ", ".join(f"`{t}`" for t in m["tests"]) or "-"))
    return "\n".join(rows)


def deps_table() -> str:
    rows = ["| module | may use (declared edges) | dependents re-tested with it |", "|---|---|---|"]
    for name in reg.MODULES:
        if reg.tier(name) == reg.ROOT:
            continue
        deps = reg.DEPENDS_ON.get(name, [])
        rows.append(f"| {name} | {', '.join(deps) or ('core only' if reg.tier(name) != reg.CORE else '-')} | "
                    f"{', '.join(sorted(reg.dependents(name))) if reg.tier(name) != reg.CORE else 'all'} |")
    return "\n".join(rows)


def events_table() -> str:
    rows = ["| event | publishers | subscribers | payload |", "|---|---|---|---|"]
    for ev, s in reg.EVENTS.items():
        rows.append(f"| `{ev}` | {', '.join(s['publishers'])} | {', '.join(s['subscribers'])} | {s['payload']} |")
    return "\n".join(rows)


def violations_table() -> str:
    cur, _ = mb.collect()
    return pair_table(mb.pair_counts(cur))


def fill(doc: str, key: str, body: str) -> str:
    b, e = BEGIN.format(key), END.format(key)
    if b not in doc:
        return doc
    i, j = doc.index(b) + len(b), doc.index(e)
    return doc[:i] + "\n" + body + "\n" + doc[j:]


def write_docs():
    with open(DOC_FILE, encoding="utf-8") as fh:
        doc = fh.read()
    for key, fn in (("modules", module_table), ("deps", deps_table), ("events", events_table),
                    ("violations", violations_table)):
        doc = fill(doc, key, fn())
    with open(DOC_FILE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(doc)
    print("docs refreshed")


if __name__ == "__main__":
    args = sys.argv[1:]
    if "--baseline" in args:
        write_baseline()
    if "--docs" in args:
        write_docs()
    if "--stats" in args or not args:
        stats()
